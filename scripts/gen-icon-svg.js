// Regenerate lib/educo-ui/icon-svg-map.generated.ts — inline SVG strings for every icon in ICON_SET.
// Browser-safe output (plain strings), so the export never needs react-dom/server in the client bundle.
// Run after changing components/website/box/icons.ts:  node scripts/gen-icon-svg.js
const fs = require("fs");
const path = require("path");
const { renderToStaticMarkup } = require("react-dom/server");
const { createElement } = require("react");
const lucide = require("lucide-react");

const root = path.resolve(__dirname, "..");
// The FULL lucide library: every PascalCase icon component (skip the `*Icon` aliases → dedupes ~half).
const names = Object.keys(lucide).filter((k) => /^[A-Z][A-Za-z0-9]+$/.test(k) && !k.endsWith("Icon") && typeof lucide[k] === "object" && lucide[k].render);

const out = {};
for (const n of names) {
  try { out[n] = renderToStaticMarkup(createElement(lucide[n], { width: "1em", height: "1em", strokeWidth: 2, "aria-hidden": true, focusable: false })); } catch {}
}
const body = "// AUTO-GENERATED by scripts/gen-icon-svg.js — do not edit. Full lucide icon set as inline SVG (browser-safe).\n"
  + "export const ICON_SVG_MAP: Record<string,string> = " + JSON.stringify(out) + ";\n";
fs.writeFileSync(path.join(root, "lib/educo-ui/icon-svg-map.generated.ts"), body);
console.log("generated", Object.keys(out).length, "icons");
