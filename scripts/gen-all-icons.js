/**
 * Generates per-source icon SVG maps + a lightweight names index, so the IconPicker can browse
 * EVERY free icon across libraries (lucide + Simple Icons + Material Symbols + Ionicons) while the
 * heavy SVG data is code-split per source and lazy-loaded on demand.
 *
 * Output (all under lib/educo-ui/):
 *   icon-svg-map.simple.generated.ts     — Record<string,string>  (Simple Icons brand logos)
 *   icon-svg-map.material.generated.ts   — Record<string,string>  (Material Symbols, outlined)
 *   icon-svg-map.ionicons.generated.ts   — Record<string,string>  (Ionicons)
 *   icon-names.generated.ts              — { simple:[], material:[], ionicons:[] } name arrays
 *
 * lucide keeps its own existing map (icon-svg-map.generated.ts) and bare names for back-compat.
 * Non-lucide names are prefixed by source ("si-", "ms-", "ion-") to avoid collisions.
 *
 * Run: node scripts/gen-all-icons.js
 */
const fs = require("fs");
const path = require("path");

const OUT = path.join(__dirname, "..", "lib", "educo-ui");

/** Normalise any raw <svg> string to inline, themeable form: 1em box + currentColor. */
function normalizeSvg(svg) {
  // drop <title> (we supply aria-label ourselves) and xml declarations
  svg = svg.replace(/<title>[\s\S]*?<\/title>/g, "").replace(/<\?xml[\s\S]*?\?>/g, "").trim();
  // ensure the root <svg ...> has width/height 1em and fill currentColor (unless it uses stroke)
  svg = svg.replace(/<svg\b([^>]*)>/, (m, attrs) => {
    let a = attrs
      .replace(/\swidth="[^"]*"/g, "")
      .replace(/\sheight="[^"]*"/g, "")
      .replace(/\srole="[^"]*"/g, "")
      .replace(/\sxmlns:xlink="[^"]*"/g, "");
    if (!/xmlns=/.test(a)) a = ' xmlns="http://www.w3.org/2000/svg"' + a;
    const usesStroke = /stroke="(?!none)/.test(svg);
    const hasFill = /\bfill="/.test(a);
    let extra = ' width="1em" height="1em"';
    if (!usesStroke && !hasFill) extra += ' fill="currentColor"';
    return `<svg${a}${extra}>`;
  });
  return svg.replace(/\s+/g, " ").replace(/> </g, "><").trim();
}

function writeMap(file, entries, label) {
  const body = entries.map(([k, v]) => `${JSON.stringify(k)}:${JSON.stringify(v)}`).join(",\n");
  const ts = `// AUTO-GENERATED by scripts/gen-all-icons.js — do not edit. Source: ${label}.\nexport const MAP: Record<string, string> = {\n${body}\n};\n`;
  fs.writeFileSync(path.join(OUT, file), ts);
  const kb = (Buffer.byteLength(ts) / 1024).toFixed(0);
  console.log(`  ${file}: ${entries.length} icons, ${kb} KB`);
  return entries.map(([k]) => k);
}

// ---- Simple Icons (brand/social logos) ----
function genSimple() {
  const si = require("simple-icons");
  const entries = [];
  for (const key of Object.keys(si)) {
    const icon = si[key];
    if (!icon || !icon.slug || !icon.path) continue;
    const name = "si-" + icon.slug;
    const svg = normalizeSvg(`<svg viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg"><path d="${icon.path}"/></svg>`);
    entries.push([name, svg]);
  }
  entries.sort((a, b) => a[0].localeCompare(b[0]));
  return writeMap("icon-svg-map.simple.generated.ts", entries, "Simple Icons");
}

// ---- Material Symbols (outlined, base weight, exclude -fill duplicates) ----
function genMaterial() {
  const dir = path.join(__dirname, "..", "node_modules", "@material-symbols", "svg-400", "outlined");
  const files = fs.readdirSync(dir).filter((f) => f.endsWith(".svg") && !f.endsWith("-fill.svg"));
  const entries = [];
  for (const f of files) {
    const raw = fs.readFileSync(path.join(dir, f), "utf8");
    const name = "ms-" + f.replace(/\.svg$/, "");
    entries.push([name, normalizeSvg(raw)]);
  }
  entries.sort((a, b) => a[0].localeCompare(b[0]));
  return writeMap("icon-svg-map.material.generated.ts", entries, "Material Symbols (outlined)");
}

// ---- Ionicons ----
function genIonicons() {
  const dir = path.join(__dirname, "..", "node_modules", "ionicons", "dist", "svg");
  const files = fs.readdirSync(dir).filter((f) => f.endsWith(".svg"));
  const entries = [];
  for (const f of files) {
    const raw = fs.readFileSync(path.join(dir, f), "utf8");
    const name = "ion-" + f.replace(/\.svg$/, "");
    entries.push([name, normalizeSvg(raw)]);
  }
  entries.sort((a, b) => a[0].localeCompare(b[0]));
  return writeMap("icon-svg-map.ionicons.generated.ts", entries, "Ionicons");
}

console.log("Generating icon maps…");
const simple = genSimple();
const material = genMaterial();
const ionicons = genIonicons();

const namesTs =
  `// AUTO-GENERATED by scripts/gen-all-icons.js — do not edit.\n` +
  `// Lightweight name index (strings only) so the picker can browse every source without loading SVG data.\n` +
  `export const SOURCE_NAMES = {\n` +
  `  simple: ${JSON.stringify(simple)},\n` +
  `  material: ${JSON.stringify(material)},\n` +
  `  ionicons: ${JSON.stringify(ionicons)},\n` +
  `} as const;\n`;
fs.writeFileSync(path.join(OUT, "icon-names.generated.ts"), namesTs);
console.log(`  icon-names.generated.ts: ${(Buffer.byteLength(namesTs) / 1024).toFixed(0)} KB`);
console.log(`Total non-lucide: ${simple.length + material.length + ionicons.length} icons`);
